export const getMetroLineColor = (routeNumber: string, city: CityType = 'moscow'): string => {
  let lines: MetroLine[] = [];
  switch (city) {
    case 'moscow':
      lines = MOSCOW_METRO_LINES;
      break;
    case 'spb':
      lines = SAINT_PETERSBURG_METRO_LINES;
      break;
    case 'ekaterinburg':
      lines = EKATERINBURG_METRO_LINES;
      break;
    case 'novosibirsk':
      lines = NOVOSIBIRSK_METRO_LINES;
      break;
    case 'nizhnynovgorod':
      lines = NIZHNY_NOVGOROD_METRO_LINES;
      break;
    case 'samara':
      lines = SAMARA_METRO_LINES;
      break;
    case 'kazan':
      lines = KAZAN_METRO_LINES;
      break;
    default:
      return '#bf5151ff';
  }
  const normalizedNumber = METRO_LINE_ALIASES[routeNumber] || routeNumber;
  const line = lines.find((l) => l.number === normalizedNumber);
  return line?.color || '#bf5151ff';
};

