export const detectMetroCity = (
  _stationName: string,
  context?: { lat?: number; lng?: number; routeNumber?: string },
): CityType => {
  if (context?.lat !== undefined && context?.lng !== undefined) {
    const { lat, lng } = context;
    // Москва и область
    if (lat >= 55.0 && lat <= 56.2 && lng >= 36.0 && lng <= 38.5) {
      return 'moscow';
    }
    // Санкт-Петербург и ближайшие окрестности
    if (lat >= 59.5 && lat <= 60.5 && lng >= 29.0 && lng <= 31.5) {
      return 'spb';
    }
    // Екатеринбург
    if (lat >= 56.5 && lat <= 57.5 && lng >= 60.0 && lng <= 61.5) {
      return 'ekaterinburg';
    }
    // Новосибирск
    if (lat >= 54.5 && lat <= 55.5 && lng >= 82.0 && lng <= 84.0) {
      return 'novosibirsk';
    }
    // Нижний Новгород
    if (lat >= 56.2 && lat <= 56.5 && lng >= 43.5 && lng <= 44.5) {
      return 'nizhnynovgorod';
    }
    // Самара
    if (lat >= 53.0 && lat <= 53.4 && lng >= 49.8 && lng <= 50.5) {
      return 'samara';
    }
    // Казань
    if (lat >= 55.6 && lat <= 56.0 && lng >= 48.5 && lng <= 49.5) {
      return 'kazan';
    }
  }
  return 'other';
};
